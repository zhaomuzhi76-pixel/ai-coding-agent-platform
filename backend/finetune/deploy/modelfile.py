"""Ollama Modelfile 生成器（D5-L0 · 纯函数）。"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from .spec import AdapterSpec

DQ3 = chr(34) * 3
SQ3 = chr(39) * 3

DEFAULT_PARAMS = (
    ("temperature", "0.7"),
    ("num_ctx", "4096"),
)

# HuggingFace repo → ollama 官方 tag（本地已 pull 时最快）
_HF_TO_OLLAMA = {
    "Qwen/Qwen2.5-0.5B-Instruct": "qwen2.5:0.5b",
    "Qwen/Qwen2.5-1.5B-Instruct": "qwen2.5:1.5b",
    "Qwen/Qwen2.5-3B-Instruct":   "qwen2.5:3b",
    "Qwen/Qwen2.5-7B-Instruct":   "qwen2.5:7b",
    "Qwen/Qwen2.5-14B-Instruct":  "qwen2.5:14b",
    "Qwen/Qwen2.5-32B-Instruct":  "qwen2.5:32b",
    "Qwen/Qwen2.5-0.5B":          "qwen2.5:0.5b",
    "Qwen/Qwen2.5-1.5B":          "qwen2.5:1.5b",
    "Qwen/Qwen2.5-7B":            "qwen2.5:7b",
}


def resolve_from_base(base_model: str) -> str:
    """把 HF repo 名解析为 ollama 能认的 FROM。

    优先级：
        1. 已知映射表命中 → ollama 官方 tag
        2. 形如 ollama tag（含 ':' 或纯名字）→ 原样
        3. 其它 HF repo → hf.co/<repo>-GGUF（ollama 拉 GGUF）
    """
    bm = (base_model or "").strip()
    if not bm:
        raise ValueError("base_model required")
    if bm in _HF_TO_OLLAMA:
        return _HF_TO_OLLAMA[bm]
    # 已经是 ollama 名字（含冒号或不含斜杠）
    if ":" in bm or "/" not in bm:
        return bm
    # HF repo → 兜底走 hf.co GGUF
    return "hf.co/" + bm


@dataclass(frozen=True, slots=True)
class ModelfileSpec:
    from_base: str
    adapter_path: str
    parameters: tuple = DEFAULT_PARAMS
    template: str = ""
    system: str = ""

    def __post_init__(self) -> None:
        if not self.from_base or not self.from_base.strip():
            raise ValueError("ModelfileSpec.from_base required")
        if not isinstance(self.parameters, tuple):
            raise TypeError("ModelfileSpec.parameters must be tuple")


def _escape_triple(text: str) -> str:
    return text.replace(DQ3, SQ3)


def build_modelfile(
    spec: AdapterSpec | None = None,
    *,
    from_base: str = "",
    adapter_path: str = "",
    parameters: tuple | None = None,
    template: str = "",
    system: str = "",
) -> str:
    if spec is not None:
        from_base = from_base or spec.base_model
        adapter_path = adapter_path or spec.adapter_path
    if not from_base or not from_base.strip():
        raise ValueError("from_base required")
    # HF repo → ollama tag 转换（否则 ollama 报 unknown model）
    from_base = resolve_from_base(from_base)
    if not isinstance(adapter_path, str) or not adapter_path.strip():
        raise ValueError("adapter_path required")

    mf = ModelfileSpec(
        from_base=from_base.strip(),
        adapter_path=adapter_path.strip(),
        parameters=tuple(parameters) if parameters is not None else DEFAULT_PARAMS,
        template=template,
        system=system,
    )

    lines: list[str] = []
    lines.append("# Auto-generated by BianCheng Finetune Deploy")
    lines.append("FROM " + mf.from_base)
    lines.append("ADAPTER " + mf.adapter_path)
    for k, v in mf.parameters:
        lines.append("PARAMETER " + k + " " + v)
    if mf.system:
        lines.append("SYSTEM " + DQ3 + _escape_triple(mf.system) + DQ3)
    if mf.template:
        lines.append("TEMPLATE " + DQ3 + _escape_triple(mf.template) + DQ3)
    lines.append("")
    return "\n".join(lines)


def _suggest_name(spec: AdapterSpec) -> str:
    base = spec.base_model.replace("/", "-").replace(":", "-").lower()
    suffix = spec.adapter_id.split("-")[-1][:6]
    return base + "-ft-" + suffix


def build_adapter_reference(spec: AdapterSpec) -> dict[str, Any]:
    name = spec.ollama_model_name or _suggest_name(spec)
    return {
        "adapter_id": spec.adapter_id,
        "name": spec.name,
        "base_model": spec.base_model,
        "adapter_path": spec.adapter_path,
        "target": spec.target.value,
        "suggested_model_name": name,
        "deploy_command": "ollama create " + name + " -f <modelfile-path>",
    }


__all__ = [
    "ModelfileSpec", "build_modelfile", "build_adapter_reference",
    "resolve_from_base",
    "DEFAULT_PARAMS", "DQ3", "SQ3",
]
