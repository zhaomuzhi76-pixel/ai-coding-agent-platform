"""Part 2 of deployer.py."""
from __future__ import annotations
from backend.core.observability.silent import swallow

from .part1 import (Callable, DEFAULT_TIMEOUT_SEC, OLLAMA_BIN, Path, _suggest_name, subprocess, time,)  # noqa
from .part1 import _run_sync  # noqa

async def run_merged_gguf_deploy(
    spec,
    *,
    on_log: Callable[[str], None] | None = None,
    on_step: Callable[[dict], None] | None = None,
) -> dict:
    """全链路：merge LoRA → 转 GGUF → ollama create。

    返回 dict（前端兼容 DeployResult 字段 + 新 steps）。
    """
    import asyncio
    from ..env_bootstrap import ensure_all
    from ..merger import merge_adapter
    from ..gguf_converter import convert_hf_to_gguf

    t0 = time.time()
    steps: list[dict] = []

    def _emit_step(ev: dict) -> None:
        if on_step is None:
            return
        try:
            on_step(ev)
        except Exception as e:
            swallow("finetune.deploy._deployer_parts.part2:32", e)

    def _step(name: str):
        s = {"name": name, "ok": False, "elapsed_sec": 0.0, "message": ""}
        steps.append(s)
        _emit_step({"type": "step", "name": name, "status": "start"})
        return s

    logs: list[str] = []

    def _sink(msg: str) -> None:
        logs.append(str(msg))
        if on_log is not None:
            try:
                on_log(str(msg))
            except Exception as e:
                swallow("finetune.deploy._deployer_parts.part2:48", e)

    def _run_sync() -> dict:
        adapter_dir = Path(spec.adapter_path)
        adapter_parent = adapter_dir.parent
        merged_dir = adapter_parent / "merged"
        gguf_dir = adapter_parent / "gguf"
        gguf_path = gguf_dir / "merged-f16.gguf"

        # step 1: env
        s1 = _step("env_bootstrap")
        t = time.time()
        try:
            _sink("[env] 准备隔离环境...")
            ensure_all(_sink)
            s1["ok"] = True
        except Exception as exc:
            s1["message"] = str(exc)
            raise
        finally:
            s1["elapsed_sec"] = round(time.time() - t, 2)
            _emit_step({"type": "step", "name": s1["name"],
                        "status": "done", "ok": s1["ok"],
                        "elapsed_sec": s1["elapsed_sec"],
                        "message": s1["message"]})

        # step 2: merge
        s2 = _step("merge_lora")
        t = time.time()
        try:
            merge_adapter(
                str(adapter_dir), spec.base_model, str(merged_dir),
                on_log=_sink,
            )
            s2["ok"] = True
        except Exception as exc:
            msg = str(exc)
            if "REJECT:" in msg or "无法合并到 GGUF" in msg:
                msg = ("本 adapter 类型不支持部署：只有 LoRA 类可合并到 GGUF。"
                       "Prefix-Tuning / Prompt-Tuning 的 virtual tokens 属于"
                       "输入层，无法合并到权重，也无法注入 ollama。")
            s2["message"] = msg
            raise RuntimeError(msg)
        finally:
            s2["elapsed_sec"] = round(time.time() - t, 2)
            _emit_step({"type": "step", "name": s2["name"],
                        "status": "done", "ok": s2["ok"],
                        "elapsed_sec": s2["elapsed_sec"],
                        "message": s2["message"]})

        # step 3: convert
        s3 = _step("convert_gguf")
        t = time.time()
        try:
            convert_hf_to_gguf(
                str(merged_dir), str(gguf_path),
                base_model=spec.base_model, on_log=_sink,
            )
            s3["ok"] = True
        except Exception as exc:
            s3["message"] = str(exc)
            raise
        finally:
            s3["elapsed_sec"] = round(time.time() - t, 2)
            _emit_step({"type": "step", "name": s3["name"],
                        "status": "done", "ok": s3["ok"],
                        "elapsed_sec": s3["elapsed_sec"],
                        "message": s3["message"]})

        # step 4: ollama create
        s4 = _step("ollama_create")
        t = time.time()
        model_name = spec.ollama_model_name or _suggest_name(spec)
        mf_text = (
            "# Auto-generated by BianCheng Finetune Deploy (merged_gguf)\n"
            f"FROM {gguf_path}\n"
            f"PARAMETER temperature 0.7\n"
            f"PARAMETER num_ctx 4096\n"
        )
        mf_path = gguf_dir / "Modelfile"
        mf_path.write_text(mf_text, encoding="utf-8")

        try:
            proc = subprocess.run(
                [OLLAMA_BIN, "create", model_name, "-f", str(mf_path)],
                capture_output=True, text=True, timeout=DEFAULT_TIMEOUT_SEC,
            )
            s4["ok"] = (proc.returncode == 0)
            s4["message"] = (proc.stderr or "")[:300] if proc.returncode != 0 else "ok"
            return {
                "ok": proc.returncode == 0,
                "adapter_id": spec.adapter_id,
                "model_name": model_name,
                "returncode": proc.returncode,
                "stdout": (proc.stdout or "")[-1000:],
                "stderr": (proc.stderr or "")[-1000:],
                "elapsed_sec": round(time.time() - t0, 2),
                "error": "" if proc.returncode == 0 else (
                    f"ollama create failed: {(proc.stderr or '')[:200]}"
                ),
            }
        finally:
            s4["elapsed_sec"] = round(time.time() - t, 2)
            _emit_step({"type": "step", "name": s4["name"],
                        "status": "done", "ok": s4["ok"],
                        "elapsed_sec": s4["elapsed_sec"],
                        "message": s4["message"]})

    try:
        result = await asyncio.to_thread(_run_sync)
    except Exception as exc:
        result = {
            "ok": False,
            "adapter_id": spec.adapter_id,
            "model_name": spec.ollama_model_name or _suggest_name(spec),
            "returncode": -1,
            "stdout": "",
            "stderr": "",
            "elapsed_sec": round(time.time() - t0, 2),
            "error": f"{type(exc).__name__}: {exc}",
        }

    result["steps"] = steps
    result["log_tail"] = logs[-40:]
    _emit_step({"type": "result", "ok": result.get("ok", False),
                "model_name": result.get("model_name", ""),
                "elapsed_sec": result.get("elapsed_sec", 0)})
    return result

